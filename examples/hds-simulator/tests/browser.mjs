import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const output = process.env.HDS_SCREENSHOTS || path.join(root, '.pio.nosync/hds-simulator-checks');
const origin = process.env.HDS_SIMULATOR_URL || 'http://127.0.0.1:18916/';
const url = new URL(origin);
assert(['127.0.0.1', 'localhost'].includes(url.hostname) && url.protocol === 'http:', 'Tests require a local simulator origin');
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH } : {}) });
const errors = [];
let checks = 0;
const check = (condition, message) => { assert(condition, message); checks++; };

async function open(context, viewport) {
  const page = await context.newPage();
  await page.setViewportSize(viewport);
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(origin);
  await page.evaluate(async () => { const app = await import('./src/app.mjs'); await app.ready; app.setPlaying(false); });
  return page;
}

const act = (page, event) => page.evaluate(async event => (await import('./src/app.mjs')).send(event), event);
const step = (page, ms) => page.evaluate(async ms => (await import('./src/app.mjs')).advanceTime(ms), ms);
const current = page => page.evaluate(async () => (await import('./src/app.mjs')).getSnapshot());
const pixels = page => page.locator('#oled').evaluate(canvas => Array.from(canvas.getContext('2d').getImageData(0, 0, 128, 64).data).filter((_, index) => index % 4 === 0));

try {
  const context = await browser.newContext({ deviceScaleFactor: 1 });
  const page = await open(context, { width: 1440, height: 960 });
  await act(page, { type: 'restart' });
  check((await current(page)).screen === 'boot', 'Restart shows boot');
  check((await pixels(page)).some(value => value > 100), 'Boot OLED is nonblank');
  await page.screenshot({ path: path.join(output, 'desktop-boot.png') });
  await step(page, 1000);
  check((await current(page)).screen === 'weighing', 'Boot transitions to weighing at 1000ms');
  check(await page.evaluate(async () => {
    const renderer = await (await import('./src/renderer.mjs')).createRenderer();
    const reference = renderer.render((await import('./src/app.mjs')).getSnapshot());
    const data = document.getElementById('oled').getContext('2d').getImageData(0, 0, 128, 64).data;
    return Array.from(reference).every((_, index) => data[index * 4] === (reference[8191 - index] ? 186 : 40));
  }), 'Canvas matches the fixed V8.1 physical mounting of real WASM pixels');
  await page.screenshot({ path: path.join(output, 'desktop-weighing.png') });
  const clockBefore = (await current(page)).now;
  await page.locator('#play-pause').click();
  await page.waitForTimeout(320);
  await page.locator('#play-pause').click();
  const clockPaused = (await current(page)).now;
  check(clockPaused > clockBefore + 200, 'Live clock advances');
  await page.waitForTimeout(150);
  check((await current(page)).now === clockPaused, 'Pause freezes the simulation clock');
  await page.locator('#step').click();
  check((await current(page)).now === clockPaused + 100, 'Step advances exactly 100ms');
  await page.locator('#weight').fill('125.4');
  await page.locator('#weight').dispatchEvent('change');
  await page.locator('#tare').click();
  let state = await current(page);
  check(state.weight === 0 && state.controls.grossWeight === 125.4, 'Tare preserves gross weight');
  await page.locator('#pour-rate').fill('12');
  await page.locator('#pour-rate').dispatchEvent('change');
  await page.locator('#pour').click();
  await step(page, 2000);
  state = await current(page);
  check(Math.abs(state.weight - 24) < 0.001, 'Pour rate follows virtual time');
  await page.locator('#pour').click();
  await page.locator('#square').focus();
  await page.keyboard.press('Space');
  check((await current(page)).timerRunning, 'Focused square keyboard tap starts timer');
  await step(page, 1600);
  check(Math.abs((await current(page)).timerMs - 1600) < 0.001, 'Timer advances with simulation clock');
  await act(page, { type: 'jump', screen: 'display' });
  await act(page, { type: 'buttonDown', name: 'circle' });
  await act(page, { type: 'buttonUp', name: 'circle' });
  await act(page, { type: 'buttonDown', name: 'square' });
  await act(page, { type: 'buttonUp', name: 'square' });
  await step(page, 1000);
  check((await current(page)).settings.screenFlipped, 'Display menu changes rotation');
  await act(page, { type: 'jump', screen: 'connections' });
  await page.screenshot({ path: path.join(output, 'desktop-menu.png') });
  await page.reload();
  await page.evaluate(async () => { const app = await import('./src/app.mjs'); await app.ready; app.setPlaying(false); });
  check((await current(page)).settings.screenFlipped, 'Menu settings survive page reload');
  await act(page, { type: 'resetDefaults' });
  await step(page, 1000);
  await act(page, { type: 'jump', screen: 'display' });
  for (let index = 0; index < 3; index++) { await act(page, { type: 'buttonDown', name: 'circle' }); await act(page, { type: 'buttonUp', name: 'circle' }); }
  await act(page, { type: 'buttonDown', name: 'square' });
  await act(page, { type: 'buttonUp', name: 'square' });
  await act(page, { type: 'jump', screen: 'weighing' });
  await step(page, 1000);
  await page.locator('#ble-connected').check();
  await page.locator('#show-prompt').click();
  state = await current(page);
  check(state.prompt.visible && state.prompt.text.includes('Carpano'), 'Manual App Text follows opt-in and connection');
  const initial = await pixels(page);
  await step(page, 999);
  check(JSON.stringify(initial) === JSON.stringify(await pixels(page)), 'Initial scroll hold is stationary');
  await step(page, 101);
  check(JSON.stringify(initial) !== JSON.stringify(await pixels(page)), 'Prompt moves after hold');
  await page.screenshot({ path: path.join(output, 'desktop-app-text.png') });
  await page.locator('#view-full').click();
  await page.screenshot({ path: path.join(output, 'desktop-full-scale.png') });
  await page.locator('#clean-view').click();
  check(await page.locator('.app-header').isHidden(), 'Clean view hides chrome');
  await page.screenshot({ path: path.join(output, 'desktop-clean.png') });
  await page.keyboard.press('Escape');
  check(await page.locator('.app-header').isVisible(), 'Escape exits clean view');
  await page.keyboard.down('c');
  await step(page, 900);
  await page.keyboard.up('c');
  check((await current(page)).prompt.cancelled && !(await current(page)).prompt.visible, 'Circle hold cancels App Text without a release tare');
  await page.locator('#ble-connected').uncheck();
  await page.locator('#ble-connected').check();
  check(!(await current(page)).prompt.cancelled, 'A new connection clears cancellation');
  await act(page, { type: 'jump', screen: 'weighing' });
  const circleBox = await page.locator('#circle').boundingBox();
  await page.mouse.move(circleBox.x + circleBox.width / 2, circleBox.y + circleBox.height / 2);
  await page.mouse.down();
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await page.mouse.up();
  await step(page, 1200);
  check(!(await current(page)).held.circle, 'Focus loss cancels held input');
  await act(page, { type: 'jump', screen: 'main' });
  await page.locator('#circle').evaluate(button => button.click());
  check((await current(page)).menu.selected === 1, 'Click-only assistive activation advances once');
  await context.close();

  const blocked = await browser.newContext();
  await blocked.addInitScript(() => {
    localStorage.setItem('unrelated-site-data', 'keep');
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function (key, value) {
      if (key === 'hds-simulator.settings.v1') throw new DOMException('Blocked', 'QuotaExceededError');
      return original.call(this, key, value);
    };
  });
  const failedSave = await open(blocked, { width: 1280, height: 900 });
  await act(failedSave, { type: 'jump', screen: 'display' });
  await act(failedSave, { type: 'buttonDown', name: 'circle' });
  await act(failedSave, { type: 'buttonUp', name: 'circle' });
  await act(failedSave, { type: 'buttonDown', name: 'square' });
  await act(failedSave, { type: 'buttonUp', name: 'square' });
  await step(failedSave, 1500);
  check((await failedSave.locator('#notice').textContent()).includes('could not be saved'), 'Save failure remains visible after clock ticks');
  await act(failedSave, { type: 'resetDefaults' });
  check(await failedSave.evaluate(() => localStorage.getItem('unrelated-site-data')) === 'keep', 'Reset defaults preserves unrelated browser data');
  await blocked.close();

  const tapsContext = await browser.newContext();
  const taps = await open(tapsContext, { width: 1280, height: 900 });
  await act(taps, { type: 'jump', screen: 'scale' });
  for (let index = 0; index < 3; index++) { await act(taps, { type: 'buttonDown', name: 'circle' }); await act(taps, { type: 'buttonUp', name: 'circle' }); }
  await act(taps, { type: 'buttonDown', name: 'square' });
  await act(taps, { type: 'buttonUp', name: 'square' });
  await act(taps, { type: 'buttonDown', name: 'circle' });
  await act(taps, { type: 'buttonUp', name: 'circle' });
  await act(taps, { type: 'buttonDown', name: 'square' });
  await act(taps, { type: 'buttonUp', name: 'square' });
  await act(taps, { type: 'jump', screen: 'weighing' });
  await step(taps, 1000);
  await act(taps, { type: 'setConnection', connected: true });
  await act(taps, { type: 'setWeight', value: 42.5 });
  await taps.locator('#double-tap').click();
  check((await current(taps)).weight === 0, 'Enabled double surface tap tares while an app is connected');
  await taps.locator('#triple-tap').click();
  check((await current(taps)).timerRunning, 'Enabled triple surface tap starts timer');
  check(await taps.locator('#double-tap').isDisabled(), 'Double surface tap is guarded while timer runs');
  await tapsContext.close();

  const liveContext = await browser.newContext();
  await liveContext.addInitScript(() => localStorage.setItem('hds-simulator.settings.v1', JSON.stringify({ version: 1, settings: { appTextEnabled: true } })));
  const live = await liveContext.newPage();
  live.on('pageerror', error => errors.push(error.message));
  await live.goto(origin);
  await live.evaluate(async () => { await (await import('./src/app.mjs')).ready; });
  await live.waitForTimeout(1150);
  await step(live, 0);
  await act(live, { type: 'setConnection', connected: true });
  await act(live, { type: 'setPrompt', text: 'Carpano Antica Sweet Vermouth: 31g' });
  const liveStart = await pixels(live);
  await live.evaluate(async () => (await import('./src/app.mjs')).setPlaying(true));
  await live.waitForTimeout(1450);
  await live.evaluate(async () => (await import('./src/app.mjs')).setPlaying(false));
  const liveMoved = await pixels(live);
  check(JSON.stringify(liveStart) !== JSON.stringify(liveMoved), 'Real-time fractional clock scrolls after the initial hold');
  await live.evaluate(async () => (await import('./src/app.mjs')).setPlaying(true));
  await live.waitForTimeout(450);
  await live.evaluate(async () => (await import('./src/app.mjs')).setPlaying(false));
  check(JSON.stringify(liveMoved) !== JSON.stringify(await pixels(live)), 'Real-time scrolling continues across successive fractional-clock frames');
  await liveContext.close();

  for (const width of [640, 390, 320]) {
    const mobile = await browser.newContext({ deviceScaleFactor: 1, isMobile: true, hasTouch: true });
    const target = await open(mobile, { width, height: 844 });
    await step(target, 1000);
    check(await target.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No horizontal overflow at ${width}px`);
    check(await target.locator('.scale-photo').isVisible(), `Scale photograph surrounds the enlarged OLED at ${width}px`);
    check(await target.locator('.oled-cover').isVisible(), `Original display is masked behind the simulated OLED at ${width}px`);
    const alignment = await target.evaluate(() => {
      const image = document.querySelector('.scale-photo').getBoundingClientRect();
      const canvas = document.getElementById('oled').getBoundingClientRect();
      return { x: (canvas.x - image.x) / image.width, y: (canvas.y - image.y) / image.height, width: canvas.width / image.width, ratio: canvas.width / canvas.height };
    });
    check(Math.abs(alignment.x - 1086 / 2362) < 0.001 && Math.abs(alignment.y - 968 / 1249) < 0.001 && Math.abs(alignment.width - 348 / 2362) < 0.001 && Math.abs(alignment.ratio - 2) < 0.01, `OLED stays aligned with photographed glass at ${width}px`);
    const button = await target.locator('#circle').boundingBox();
    check(button.width >= 44 && button.height >= 44, `Touch targets at ${width}px`);
    const photoBox = await target.locator('.scale-photo').boundingBox();
    check(button.width >= photoBox.width * 127 / 2362 - 1, `Hitbox covers the entire photographed button at ${width}px`);
    await target.locator('#scene').selectOption('main');
    await target.locator('#circle').tap();
    check((await current(target)).menu.selected === 1, `Touch menu navigation at ${width}px`);
    await target.touchscreen.tap(button.x + 3, button.y + button.height / 2);
    check((await current(target)).menu.selected === 2, `Button edge remains tappable at ${width}px`);
    await target.screenshot({ path: path.join(output, `mobile-${width}.png`), fullPage: true });
    await target.locator('#clean-view').tap();
    const exitState = await target.locator('#exit-clean').evaluate(button => ({ opacity: getComputedStyle(button).opacity, clean: document.body.classList.contains('clean'), coarse: matchMedia('(pointer: coarse)').matches, hover: matchMedia('(hover: none)').matches }));
    check(exitState.opacity === '1' && exitState.clean, `Clean-view exit is discoverable on touch at ${width}px: ${JSON.stringify(exitState)}`);
    await target.locator('#exit-clean').tap();
    check(await target.locator('.app-header').isVisible(), `Touch exit restores controls at ${width}px`);
    await target.locator('#view-full').tap();
    check(await target.locator('.scale-photo').isVisible(), `Full-scale photo remains visible at ${width}px`);
    const fullButton = await target.locator('#circle').boundingBox();
    check(fullButton.width >= 44 && fullButton.height >= 44, `Full-scale touch target at ${width}px`);
    await mobile.close();
  }
  check(errors.length === 0, `Browser errors: ${errors.join('; ')}`);
  console.log(`HDS simulator browser checks passed: ${checks}; screenshots: ${output}`);
} finally {
  await browser.close();
}
